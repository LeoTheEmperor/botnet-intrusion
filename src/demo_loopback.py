#!/usr/bin/env python3
"""
Single-machine LIVE demo (Linux, or WSL2): REAL packets captured from the kernel on the loopback interface, the whole
pipeline running live on one computer, no Raspberry Pi and no second machine.

  1. records a labelled session: traffic_sim sends benign / SYN-flood-like / UDP-flood-like / port-scan-like traffic to
     127.0.0.2 while live_detector captures it on 'lo' and labels it from marker packets
  2. trains a model on that recording
  3. runs the detector LIVE on 'lo' with the web dashboard while fresh traffic is generated (no markers this time)

    sudo python3 src/demo_loopback.py            # then open http://localhost:8080

Needs root (raw socket) and numpy. The traffic is generated by us on this machine, so it only shows that live capture,
features, classification and dashboard work together; it says nothing about real-world accuracy. Say so when you demo it.
"""
import argparse
import os
import subprocess
import sys
import threading
import time
import webbrowser
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src"
SEQ = ["benign", "syn_flood", "benign", "udp_flood", "benign", "port_scan", "benign"]


def cmd(script, *args):
    return [sys.executable, str(SRC / script), *map(str, args)]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--segment", type=float, default=8.0, help="seconds per traffic segment (7 segments per round)")
    ap.add_argument("--loops", type=int, default=2, help="how many rounds of traffic during the live part")
    ap.add_argument("--port", type=int, default=8080)
    ap.add_argument("--lan", action="store_true", help="serve on 0.0.0.0 (other devices on YOUR network can open the page)")
    ap.add_argument("--regen", action="store_true", help="re-record and retrain even if a model exists")
    ap.add_argument("--no-browser", action="store_true")
    a = ap.parse_args()

    if not sys.platform.startswith("linux"):
        sys.exit("this demo needs Linux (raw AF_PACKET sockets). On Windows use WSL2, or run demo_nbaiot.py / demo_replay.py instead.")
    if os.geteuid() != 0:
        sys.exit("raw packet capture needs root: run it as  sudo python3 src/demo_loopback.py")

    seg = f"{a.segment:g}"
    plan = ",".join(f"{label}:{seg}" for label in SEQ)
    total = a.segment * len(SEQ)
    model, session_dir = ROOT / "models" / "loopback_model.npz", ROOT / "data" / "live_demo_lo"
    common = ["--target", "127.0.0.2", "--i-own-this-network"]

    if a.regen or not model.exists():
        print(f"== 1/3 recording a labelled live session on 'lo' ({total:.0f} s) ==", flush=True)
        session = session_dir / "session.csv"
        session.unlink(missing_ok=True)
        rec = subprocess.Popen(cmd("live_detector.py", "collect", "--iface", "lo", "--markers", ",".join(dict.fromkeys(SEQ)),
                                   "--trim-edges", 0.5, "--warmup", 20, "--duration", total + 6, "--out", session), cwd=ROOT)
        time.sleep(1.5)
        subprocess.run(cmd("traffic_sim.py", "session", *common, "--plan", plan), check=True, cwd=ROOT)
        rec.wait()
        print("== 2/3 training ==", flush=True)
        subprocess.run(cmd("train_live_model.py", "--data", session_dir, "--out", model, "--trees", 20, "--final"), check=True, cwd=ROOT)

    print(f"== 3/3 LIVE detection on 'lo' ({a.loops} round(s) of {total:.0f} s) ==", flush=True)
    det_args = ["detect", "--iface", "lo", "--model", model, "--window", 1, "--dashboard", a.port,
                "--duration", total * a.loops + 8]
    if a.lan:
        det_args += ["--dashboard-host", "0.0.0.0"]
    det = subprocess.Popen(cmd("live_detector.py", *det_args), cwd=ROOT)
    time.sleep(2.0)
    url = f"http://localhost:{a.port}/"
    print(f"open {url} in a browser now", flush=True)
    if not a.no_browser:
        threading.Timer(0.5, webbrowser.open, [url]).start()
    try:
        for _ in range(a.loops):
            subprocess.run(cmd("traffic_sim.py", "session", *common, "--plan", plan, "--no-markers"), check=True, cwd=ROOT)
        det.wait()
    except KeyboardInterrupt:
        det.terminate()


if __name__ == "__main__":
    main()
